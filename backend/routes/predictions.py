import os
import json
from fastapi import APIRouter, Depends, Query
from sqlalchemy.orm import Session
from typing import List, Optional, Dict, Any

from backend.config import settings
from backend.database import get_db
from backend.schemas import TrafficPredictionResponse
from backend.services import traffic_service

router = APIRouter(prefix="/api", tags=["Predictions"])

@router.get("/predictions", response_model=List[TrafficPredictionResponse])
def get_predictions(
    road_id: Optional[str] = Query(None, description="Filter predictions by Road ID"),
    limit: int = Query(50, ge=1, le=200, description="Max predictions to return"),
    db: Session = Depends(get_db)
):
    """Retrieve 15-minute future traffic predictions generated by Random Forest."""
    return traffic_service.get_predictions_list(db, road_id=road_id, limit=limit)

@router.get("/predictions/evaluation")
def get_model_evaluation_metrics() -> Dict[str, Any]:
    """Retrieve rigorous model performance metrics (MAE, RMSE, R²) computed on holdout test set."""
    metrics_path = settings.METRICS_PATH
    if os.path.exists(metrics_path):
        with open(metrics_path, "r") as f:
            return json.load(f)
    return {
        "status": "pending_training",
        "message": "Metrics not found. Run ml/train_model.py to generate."
    }

